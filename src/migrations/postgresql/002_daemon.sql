CREATE OR REPLACE FUNCTION sashiko_day(epoch BIGINT) RETURNS TEXT
LANGUAGE SQL IMMUTABLE STRICT PARALLEL SAFE AS $$
    SELECT to_char(to_timestamp(epoch) AT TIME ZONE 'UTC', 'YYYY-MM-DD')
$$;
CREATE OR REPLACE FUNCTION sashiko_datetime(epoch BIGINT) RETURNS TEXT
LANGUAGE SQL IMMUTABLE STRICT PARALLEL SAFE AS $$
    SELECT to_char(to_timestamp(epoch) AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
$$;
